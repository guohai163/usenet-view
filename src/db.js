import pg from 'pg';
import { discussionKey } from './article.js';

async function backfillDiscussions(client) {
  let cursor = ['0', '0'];
  while (true) {
    const { rows } = await client.query(`
      SELECT group_id, number, message_id, substring(raw FOR 65536) AS headers
      FROM usenet_articles
      WHERE (group_id, number) > ($1::bigint, $2::bigint)
      ORDER BY group_id, number LIMIT 500
    `, cursor);
    if (!rows.length) return;
    const discussions = rows.map(row => ({
      group_id: row.group_id,
      number: row.number,
      thread_key: discussionKey(row.headers, row.message_id),
    }));
    await client.query(`
      UPDATE usenet_articles AS a SET thread_key = b.thread_key
      FROM jsonb_to_recordset($1::jsonb) AS b(group_id bigint, number bigint, thread_key text)
      WHERE a.group_id = b.group_id AND a.number = b.number
    `, [JSON.stringify(discussions)]);
    const last = rows.at(-1);
    cursor = [last.group_id, last.number];
  }
}

export function openDatabase(databaseUrl) {
  const pool = new pg.Pool({ connectionString: databaseUrl, connectionTimeoutMillis: 10000 });
  pool.on('error', error => console.error('PostgreSQL:', error.message));
  return pool;
}

export async function initializeDatabase(pool) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query("SELECT pg_advisory_xact_lock(hashtextextended('cnusenet:schema', 0))");
    await client.query(`
      CREATE TABLE IF NOT EXISTS usenet_groups (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source text COLLATE "C" NOT NULL,
        name text COLLATE "C" NOT NULL,
        low_article bigint NOT NULL,
        high_article bigint NOT NULL,
        remote_status text NOT NULL,
        active boolean NOT NULL DEFAULT true,
        synced_through bigint,
        synced_at timestamptz,
        article_count bigint NOT NULL DEFAULT 0,
        UNIQUE (source, name)
      );

      CREATE TABLE IF NOT EXISTS usenet_articles (
        group_id bigint NOT NULL REFERENCES usenet_groups(id),
        number bigint NOT NULL,
        message_id text NOT NULL,
        subject text NOT NULL,
        author text NOT NULL,
        posted_at timestamptz,
        body text NOT NULL,
        raw bytea NOT NULL,
        PRIMARY KEY (group_id, number)
      );
    `);
    const { rows: [schema] } = await client.query(`
      SELECT EXISTS (
        SELECT 1 FROM pg_attribute WHERE attrelid = 'usenet_articles'::regclass AND attname = 'thread_key' AND NOT attisdropped
      ) AS has_discussions
    `);
    if (!schema.has_discussions) {
      await client.query('ALTER TABLE usenet_articles ADD COLUMN thread_key text');
      await backfillDiscussions(client);
    }
    await client.query('CREATE INDEX IF NOT EXISTS usenet_articles_thread ON usenet_articles (group_id, thread_key, number)');
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
