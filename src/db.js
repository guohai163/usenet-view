import pg from 'pg';
import { articleDecodeVersion, decodeArticleFields, discussionKey } from './article.js';

export async function refreshArticleText(pool, signal) {
  const db = await pool.connect();
  let cursor = ['0', '0'];
  let updated = 0;
  let failed = 0;
  try {
    const { rows: [lock] } = await db.query(
      "SELECT pg_try_advisory_lock(hashtextextended('cnusenet:article-text', 0)) AS acquired",
    );
    if (!lock.acquired) return;

    while (!signal.aborted) {
      const { rows } = await db.query(`
        WITH candidates AS (
          SELECT group_id, number, octet_length(raw) AS bytes
          FROM usenet_articles
          WHERE decode_version < $3 AND (group_id, number) > ($1::bigint, $2::bigint)
          ORDER BY group_id, number LIMIT 100
        ), batch AS (
          SELECT group_id, number, sum(bytes) OVER (ORDER BY group_id, number) - bytes AS preceding_bytes
          FROM candidates
        )
        SELECT a.group_id, a.number, a.raw
        FROM batch JOIN usenet_articles AS a USING (group_id, number)
        WHERE preceding_bytes < 8 * 1024 * 1024
        ORDER BY a.group_id, a.number
      `, [...cursor, articleDecodeVersion]);
      if (!rows.length) break;

      const decoded = [];
      for (const row of rows) {
        if (signal.aborted) break;
        try {
          const { subject, author, body, sourceText } = await decodeArticleFields(row.raw);
          decoded.push({ group_id: row.group_id, number: row.number, subject, author, body, source_text: sourceText });
        } catch (error) {
          failed += 1;
          console.error(`文章 ${row.group_id}/${row.number} 解码失败：${error.message}`);
        }
      }
      if (decoded.length) {
        const { rowCount } = await db.query(`
          UPDATE usenet_articles AS a
          SET subject = b.subject, author = b.author, body = b.body, source_text = b.source_text, decode_version = $2
          FROM jsonb_to_recordset($1::jsonb) AS b(
            group_id bigint, number bigint, subject text, author text, body text, source_text text
          )
          WHERE a.group_id = b.group_id AND a.number = b.number AND a.decode_version < $2
        `, [JSON.stringify(decoded), articleDecodeVersion]);
        updated += rowCount;
      }
      const last = rows.at(-1);
      cursor = [last.group_id, last.number];
    }
  } finally {
    db.release(true);
  }
  if (updated || failed) console.log(`存档重新解码：${updated} 篇，失败 ${failed} 篇。`);
}

async function backfillDiscussions(client) {
  let cursor = ['0', '0'];
  while (true) {
    const { rows } = await client.query(`
      SELECT group_id, number, message_id, substring(raw FOR 65536) AS headers
      FROM usenet_articles
      WHERE (group_id, number) > ($1::bigint, $2::bigint)
      ORDER BY group_id, number LIMIT 500
    `, cursor);
    if (!rows.length) return;
    const discussions = rows.map(row => ({
      group_id: row.group_id,
      number: row.number,
      thread_key: discussionKey(row.headers, row.message_id),
    }));
    await client.query(`
      UPDATE usenet_articles AS a SET thread_key = b.thread_key
      FROM jsonb_to_recordset($1::jsonb) AS b(group_id bigint, number bigint, thread_key text)
      WHERE a.group_id = b.group_id AND a.number = b.number
    `, [JSON.stringify(discussions)]);
    const last = rows.at(-1);
    cursor = [last.group_id, last.number];
  }
}

export function openDatabase(databaseUrl) {
  const pool = new pg.Pool({ connectionString: databaseUrl, connectionTimeoutMillis: 10000 });
  pool.on('error', error => console.error('PostgreSQL:', error.message));
  return pool;
}

export async function initializeDatabase(pool) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query("SELECT pg_advisory_xact_lock(hashtextextended('cnusenet:schema', 0))");
    await client.query(`
      CREATE TABLE IF NOT EXISTS usenet_groups (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source text COLLATE "C" NOT NULL,
        name text COLLATE "C" NOT NULL,
        low_article bigint NOT NULL,
        high_article bigint NOT NULL,
        remote_status text NOT NULL,
        active boolean NOT NULL DEFAULT true,
        synced_through bigint,
        synced_at timestamptz,
        article_count bigint NOT NULL DEFAULT 0,
        UNIQUE (source, name)
      );

      CREATE TABLE IF NOT EXISTS usenet_articles (
        group_id bigint NOT NULL REFERENCES usenet_groups(id),
        number bigint NOT NULL,
        message_id text NOT NULL,
        subject text NOT NULL,
        author text NOT NULL,
        posted_at timestamptz,
        body text NOT NULL,
        source_text text,
        raw bytea NOT NULL,
        decode_version integer NOT NULL DEFAULT 0,
        PRIMARY KEY (group_id, number)
      );
    `);
    const { rows: [schema] } = await client.query(`
      SELECT EXISTS (
        SELECT 1 FROM pg_attribute WHERE attrelid = 'usenet_articles'::regclass AND attname = 'thread_key' AND NOT attisdropped
      ) AS has_discussions
    `);
    if (!schema.has_discussions) {
      await client.query('ALTER TABLE usenet_articles ADD COLUMN thread_key text');
      await backfillDiscussions(client);
    }
    await client.query('CREATE INDEX IF NOT EXISTS usenet_articles_thread ON usenet_articles (group_id, thread_key, number)');
    await client.query('ALTER TABLE usenet_articles ADD COLUMN IF NOT EXISTS decode_version integer NOT NULL DEFAULT 0');
    await client.query('ALTER TABLE usenet_articles ADD COLUMN IF NOT EXISTS source_text text');
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
